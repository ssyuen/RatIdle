// Bundles ../web/index.html into src/gameHtml.ts so the app runs offline:
// three.js is inlined from node_modules and the pixel font is embedded when it can be downloaded.
// The Firebase web API key for cloud saves comes from FIREBASE_API_KEY (an EAS environment variable in cloud builds)
// or from mobile/.env.local, which git ignores. The output file is git-ignored too, since it then contains the key.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const gamePath = resolve(root, '../web/index.html');
const threePath = resolve(root, 'node_modules/three/build/three.min.js');
const outPath = resolve(root, 'src/gameHtml.ts');

let html = readFileSync(gamePath, 'utf8').replace(/^<!doctype html>\n/i, '');

const envPath = resolve(root, '.env.local');
const envFile = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
const apiKey = (process.env.FIREBASE_API_KEY || envFile.match(/^FIREBASE_API_KEY=["']?([\w-]+)/m)?.[1] || '').trim();
if (!html.includes("'__FIREBASE_API_KEY__'")) throw new Error('Firebase API key placeholder not found in game HTML');
if (/^AIza[\w-]{35}$/.test(apiKey)) html = html.replace("'__FIREBASE_API_KEY__'", () => `'${apiKey}'`);
else console.warn('No FIREBASE_API_KEY set (env or mobile/.env.local): cloud saves will be hidden in this build.');
const three = readFileSync(threePath, 'utf8').replace(/<\/script/gi, '<\\/script');

const threeTag = '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>';
if (!html.includes(threeTag)) throw new Error('three.js <script> tag not found in game HTML');
html = html.replace(threeTag, () => `<script>${three}</script>`);

// Embed the Pixelify Sans font so text looks right without a network connection.
const fontLink = /<link rel="stylesheet" href="(https:\/\/fonts\.googleapis\.com\/[^"]+)">/;
const m = html.match(fontLink);
if (m) {
  try {
    const ua = 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1';
    let css = await (await fetch(m[1].replace(/&amp;/g, '&'), { headers: { 'User-Agent': ua } })).text();
    // Keep only the latin subset to stay small.
    if (css.includes('/* latin */')) {
      css = css.split('/*').filter(b => b.startsWith(' latin */')).map(b => '/*' + b).join('');
    }
    for (const url of new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)]+/g) || [])) {
      const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
      css = css.split(url).join(`data:font/woff2;base64,${buf.toString('base64')}`);
    }
    html = html.replace(fontLink, () => `<style>${css}</style>`);
    console.log('Embedded Pixelify Sans font.');
  } catch (e) {
    console.warn('Could not embed font (will load from Google Fonts at runtime):', e.message);
  }
}
html = html.replace(/<link rel="preconnect"[^>]*>\n?/g, '');

const doc = `<!doctype html>
<html lang="en">
<head>
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
</head>
<body>
${html}
</body>
</html>`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `// Generated by scripts/build-game.mjs from ../web/index.html. Do not edit by hand.\nexport const GAME_HTML = ${JSON.stringify(doc)};\n`);
console.log(`Wrote ${outPath} (${(doc.length / 1024).toFixed(0)} KB)`);
